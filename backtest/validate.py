# Random-entry null model — "is this alpha, or beta wearing a costume?"
# ---------------------------------------------------------------------------


@dataclass
class NullModelResult:
    strategy_expectancy: float
    null_expectancy: float        # mean across seeds of random-entry expectancy
    alpha: float                  # strategy − null
    p_value: float                # fraction of seeds that matched/beat the strategy
    n_strategy_trades: int
    n_null_trades_avg: int
    n_seeds: int

    @property
    def verdict(self) -> str:
        if self.p_value <= 0.05:
            return "🟢 진입 신호가 무작위를 유의하게 상회 (알파 가능성)"
        if self.p_value <= 0.20:
            return "🟡 미약 — 무작위 대비 우위가 불확실"
        return "🔴 무작위와 구분 안 됨 — 수익원은 진입 신호가 아니라 보유 자체(베타)"


def random_entry_null(
    series: dict[str, list[dict]],
    p: Params,
    *,
    n_seeds: int = 20,
    seed_base: int = 0,
) -> NullModelResult | None:
    """Compare a strategy against coin-flip entries under identical exits.

    The single most important control for a backtest run over one market
    regime. A rising market pays *any* strategy that holds equities, so a
    positive expectancy proves nothing on its own — the question is
    whether the entry rule beats entering at random with the same
    frequency and the same stop/take/max-hold discipline.

    Entry probability is calibrated so the null model opens roughly as
    many trades as the strategy did, keeping cost drag and sample size
    comparable. ``p_value`` is the fraction of random seeds whose
    expectancy matched or beat the strategy's: > 0.05 means the strategy
    is not distinguishable from luck.

    Interpretation trap this is designed to catch (observed 2026-07-25 on
    the live config's cache): stretching the holding period lifted net
    expectancy from +0.002% to +3.8%/trade, which looks like a discovered
    edge — but random entry earned +4.0% over the same bars. The gain was
    market drift, and the signal was contributing nothing.
    """
    strat = run_backtest(series, p).trades
    if not strat:
        return None
    strat_exp = mean(t.net_pct for t in strat)

    # Match trade count: each trade occupies ~max_hold_days bars, so this
    # entry rate reproduces the strategy's turnover (and thus its total
    # cost drag) rather than letting the null trade far more or less.
    total_bars = sum(len(b) for b in series.values())
    if total_bars <= 0:
        return None
    entry_rate = min(0.95, max(0.001, len(strat) * max(p.max_hold_days, 1) / total_bars))

    normalized = {code: normalize_rows(bars) for code, bars in series.items()}
    null_exps: list[float] = []
    null_counts: list[int] = []
    for s in range(n_seeds):
        rng = random.Random(seed_base + s)
        trades: list[Trade] = []
        for code, rows in normalized.items():
            trades.extend(
                simulate_exits(code, rows, p, lambda _r, _i: rng.random() < entry_rate)
            )
        if trades:
            null_exps.append(mean(t.net_pct for t in trades))
            null_counts.append(len(trades))
    if not null_exps:
        return None

    beat = sum(1 for x in null_exps if x >= strat_exp) / len(null_exps)
    return NullModelResult(
        strategy_expectancy=round(strat_exp, 4),
        null_expectancy=round(mean(null_exps), 4),
        alpha=round(strat_exp - mean(null_exps), 4),
        p_value=round(beat, 4),
        n_strategy_trades=len(strat),
        n_null_trades_avg=int(mean(null_counts)),
        n_seeds=len(null_exps),
    )


